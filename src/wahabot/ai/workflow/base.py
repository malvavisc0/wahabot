"""Attribute contract shared by the workflow and its mixins."""

# pyright: reportUninitializedInstanceVariable=false

import asyncio
from collections.abc import Callable
from typing import Any

from llama_index.core.base.llms.types import ChatMessage
from llama_index.core.llms.function_calling import FunctionCallingLLM
from llama_index.core.tools import BaseTool

from wahabot.ai.triage import TriageGate, TriageResult
from wahabot.core.learned import RecapMerger
from wahabot.core.notebook import Notebook
from wahabot.core.thread_index import ThreadIndexer
from wahabot.core.tickets.store import TicketStore
from wahabot.settings import Settings


class AgentBase:
    """Attributes assigned by ``FunctionCallingAgentWorkflow.__init__``."""

    tools: list[BaseTool]
    system_prompt: str | None
    prompt_renderer: Callable[[], str] | None
    llm: FunctionCallingLLM
    memory_token_limit: int
    tool_round_limit: int
    llm_semaphore: asyncio.Semaphore
    settings: Settings | None
    notebook: Notebook | None
    rules_renderer: Callable[[], str] | None
    gate_rules_renderer: Callable[[], str] | None
    triage: TriageGate | None
    triage_tasks: dict[int, asyncio.Task[TriageResult]]
    recap_merger: RecapMerger | None
    thread_index: ThreadIndexer | None
    ticket_store: TicketStore | None

    def audit(self, kind: str, **fields: Any) -> None: ...

    def system_message(self) -> ChatMessage | None: ...

    def rendered_session_rules(self) -> str: ...

    def rendered_gate_rules(self) -> str: ...

    def stored_triage_result(self, *args: Any, **kwargs: Any) -> Any: ...
    def with_image(self, *args: Any, **kwargs: Any) -> Any: ...
    async def chat_history(self, *args: Any, **kwargs: Any) -> Any: ...
    async def rewrite_blame(self, *args: Any, **kwargs: Any) -> Any: ...
    def log_silence_reason(self, *args: Any, **kwargs: Any) -> Any: ...
    def stopped_response(self, *args: Any, **kwargs: Any) -> Any: ...
    def repeats_tool_call(self, *args: Any, **kwargs: Any) -> Any: ...
    def delivery_complete(self, *args: Any, **kwargs: Any) -> Any: ...
    async def wrap_up_response(self, *args: Any, **kwargs: Any) -> Any: ...
    async def remember(self, *args: Any, **kwargs: Any) -> Any: ...
    async def mark_turn_handled(self, *args: Any, **kwargs: Any) -> Any: ...
    def collapse_delivery(self, *args: Any, **kwargs: Any) -> Any: ...
    def warn_accidental_silence(self, *args: Any, **kwargs: Any) -> Any: ...
    def any_delivery(self, *args: Any, **kwargs: Any) -> Any: ...
    async def store_wrap_up_note(self, *args: Any, **kwargs: Any) -> Any: ...
    def audit_wrap_up_note(self, *args: Any, **kwargs: Any) -> Any: ...
    def drop_post_delivery_text(self, *args: Any, **kwargs: Any) -> Any: ...
    async def ensure_memory(self, *args: Any, **kwargs: Any) -> Any: ...
